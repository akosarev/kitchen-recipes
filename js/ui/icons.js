/**
 * An icon as inline SVG markup (decorative: aria-hidden). Unknown names render nothing.
 * @param {string} name
 * @param {string} [cls]
 */
export function icon(name, cls = "ic") {
  const p = PATHS[name];
  if (!p) return "";
  return `<svg class="${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${p}</svg>`;
}

/** Icon names, for tests. */
export const ICONS = Object.keys(PATHS);

/**
 * The icon for a step's technique. Only techniques with a clear picture have one: mixing a sauce,
 * tossing and "other" show none rather than a glyph that needs explaining.
 * @type {Readonly<Record<string, string>>}
 */
export const TECHNIQUE_ICON = Object.freeze({
  chop: "cut",
  boil: "pot", simmer: "pot",
  fry: "flame", stirfry: "flame",
  soak: "wait", rest: "wait",
  plate: "platter",
});

/**
 * A step's technique icon as markup, or "" when the technique has none.
 * @param {{ technique?: string }} step
 * @param {string} [cls]
 */
export function techniqueIcon(step, cls = "ic") {
  const name = step.technique === undefined ? undefined : (Object.hasOwn(TECHNIQUE_ICON, step.technique) ? TECHNIQUE_ICON[step.technique] : undefined);
  return name ? icon(name, cls) : "";
}
